// ===== ELEMENTOS =====
const html = document.documentElement;
const btnTema = document.getElementById('btnTema');
const btnIdioma = document.getElementById('btnIdioma');
const icone = btnTema.querySelector('i');
const nav = document.getElementById('navPrincipal');

let idiomaAtual = localStorage.getItem('idioma') || 'pt';

// ===== TEMA CLARO / ESCURO =====
function aplicarTema(tema) {
  html.setAttribute('data-bs-theme', tema);
  localStorage.setItem('tema', tema);
  icone.className = tema === 'dark' ? 'bi bi-sun' : 'bi bi-moon-stars';
  btnTema.title = tema === 'dark' ? textos[idiomaAtual].temaClaro : textos[idiomaAtual].temaEscuro;
}

btnTema.addEventListener('click', () => {
  const atual = html.getAttribute('data-bs-theme');
  aplicarTema(atual === 'dark' ? 'light' : 'dark');
});

// ===== EFEITO DE DIGITAÇÃO =====
const velocidadeDigitacao = 55; // milissegundos por letra (diminua para mais rápido)
const reduzirMovimento = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
const timersDigitacao = new Set();

// Para qualquer digitação em andamento (usado ao trocar de idioma)
function pararDigitacao() {
  timersDigitacao.forEach((timer) => clearInterval(timer));
  timersDigitacao.clear();
  document.querySelectorAll('.digitando').forEach((el) => el.classList.remove('digitando'));
}

// Digita o texto dentro do elemento. Ao terminar, chama "aoTerminar" (se houver)
function digitarTexto(el, texto, aoTerminar) {
  if (reduzirMovimento) {
    el.textContent = texto;
    if (aoTerminar) aoTerminar();
    return;
  }

  const letras = [...texto];
  el.textContent = '';
  el.classList.add('digitando');

  let i = 0;
  const timer = setInterval(() => {
    i++;
    el.textContent = letras.slice(0, i).join('');

    if (i >= letras.length) {
      clearInterval(timer);
      timersDigitacao.delete(timer);
      el.classList.remove('digitando');
      if (aoTerminar) aoTerminar();
    }
  }, velocidadeDigitacao);

  timersDigitacao.add(timer);
}

// ===== IDIOMA (PT / EN) =====
function aplicarIdioma(idioma) {
  pararDigitacao();

  idiomaAtual = idioma;
  localStorage.setItem('idioma', idioma);
  html.setAttribute('lang', idioma === 'pt' ? 'pt-BR' : 'en');

  document.querySelectorAll('[data-i18n]').forEach((elemento) => {
    const chave = elemento.getAttribute('data-i18n');
    if (textos[idioma][chave]) {
      elemento.textContent = textos[idioma][chave];
    }
  });

  // O botão mostra o idioma para onde a troca vai levar
  btnIdioma.textContent = idioma === 'pt' ? 'EN' : 'PT';
  btnIdioma.title = idioma === 'pt' ? 'Switch to English' : 'Mudar para português';

  // Atualiza o título do botão de tema no novo idioma
  aplicarTema(html.getAttribute('data-bs-theme'));
}

btnIdioma.addEventListener('click', () => {
  aplicarIdioma(idiomaAtual === 'pt' ? 'en' : 'pt');
});

// ===== NAVBAR TRANSLÚCIDA AO ROLAR =====
function atualizarNavbar() {
  nav.classList.toggle('navbar-scrolled', window.scrollY > 40);
}

window.addEventListener('scroll', atualizarNavbar, { passive: true });

// ===== MENU ACOMPANHA A SEÇÃO VISÍVEL =====
const linksMenu = document.querySelectorAll('#navPrincipal .nav-link');
const secoes = document.querySelectorAll('section[id]');

const observador = new IntersectionObserver((entradas) => {
  entradas.forEach((entrada) => {
    if (entrada.isIntersecting) {
      const idAtual = '#' + entrada.target.id;
      linksMenu.forEach((link) => {
        link.classList.toggle('active', link.getAttribute('href') === idAtual);
      });
    }
  });
}, {
  rootMargin: '-50% 0px -50% 0px'
});

secoes.forEach((secao) => observador.observe(secao));

// ===== BARRA DE PROGRESSO DA FORMAÇÃO =====
const boxProgresso = document.getElementById('progressoFormacao');
const numeroProgresso = boxProgresso.querySelector('.progress-numero');
const preenchimento = boxProgresso.querySelector('.progress-fill');
const statusProgresso = boxProgresso.querySelector('.progress-status');
const metaProgresso = parseInt(boxProgresso.dataset.progresso, 10);
let animacaoTerminou = false;

function atualizarStatusProgresso() {
  const t = textos[idiomaAtual];
  if (!animacaoTerminou) {
    statusProgresso.textContent = t.progCarregando;
  } else {
    statusProgresso.textContent = metaProgresso >= 100 ? t.progConcluido : t.progAndamento;
  }
}

function animarProgresso() {
  preenchimento.style.width = metaProgresso + '%';
  const duracao = 1600;
  const inicio = performance.now();

  function passo(agora) {
    const fracao = Math.min((agora - inicio) / duracao, 1);
    numeroProgresso.textContent = Math.round(fracao * metaProgresso);

    if (fracao < 1) {
      requestAnimationFrame(passo);
    } else {
      animacaoTerminou = true;
      if (metaProgresso >= 100) boxProgresso.classList.add('concluido');
      atualizarStatusProgresso();
    }
  }

  requestAnimationFrame(passo);
}

// A animação só começa quando pelo menos metade da barra aparece na tela
const observadorProgresso = new IntersectionObserver((entradas, obs) => {
  if (entradas[0].isIntersecting) {
    animarProgresso();
    obs.disconnect();
  }
}, { threshold: 0.5 });

observadorProgresso.observe(boxProgresso);

// Atualiza o texto de status quando o idioma muda
btnIdioma.addEventListener('click', atualizarStatusProgresso);
atualizarStatusProgresso();

// ===== HERO: "OLÁ, EU SOU" E DEPOIS O NOME =====
const tituloOla = document.querySelector('.hero .section-title[data-i18n="heroOla"]');
const tituloNome = document.querySelector('.hero .section-title[data-i18n="heroNome"]');

function digitarHero() {
  if (!tituloOla || !tituloNome) return;
  const t = textos[idiomaAtual];

  // Limpa os dois títulos antes de começar, para o nome não aparecer antes da hora
  tituloOla.textContent = '';
  tituloNome.textContent = '';

  digitarTexto(tituloOla, t.heroOla, () => {
    digitarTexto(tituloNome, t.heroNome);
  });
}

// ===== DEMAIS TÍTULOS: DIGITAM AO APARECER NA TELA =====
const titulosSecao = [...document.querySelectorAll('.section-title')]
  .filter((titulo) => !titulo.closest('.hero'));

const observadorTitulos = new IntersectionObserver((entradas) => {
  entradas.forEach((entrada) => {
    if (entrada.isIntersecting) {
      const titulo = entrada.target;
      if (titulo.dataset.digitado !== 'sim') {
        titulo.dataset.digitado = 'sim';
        digitarTexto(titulo, titulo.textContent.trim());
      }
      observadorTitulos.unobserve(titulo);
    }
  });
}, { threshold: 0.6 });

titulosSecao.forEach((titulo) => observadorTitulos.observe(titulo));

// ===== INICIALIZAÇÃO =====
aplicarTema(localStorage.getItem('tema') || 'dark');
aplicarIdioma(idiomaAtual);
atualizarNavbar();
digitarHero();